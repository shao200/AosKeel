def _snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
def _load_dir(sub: str) -> list[dict]:
    out = []
    for p in sorted((ROOT / "spec" / sub).glob("*.yaml")):
        out.append(yaml.safe_load(p.read_text(encoding="utf-8")) or {})
    return out
def _spec_ref() -> str:
    caps = load_caps()
    m = re.search(r"spec_ref:\s*(AOS-ART-\d+)",
                  (ROOT / "config/capabilities.yaml").read_text(encoding="utf-8"))
    return m.group(1) if m else str(caps.get("spec_ref", "UNKNOWN"))
def _render_actions(actions: list[dict]) -> str:
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— 声明即代码（KS-4.3 的骨架形态）。',
        f"spec_ref: {_spec_ref()} · 再生成: aos generate --force（正常路径先改 spec/ 声明）",
        "禁止手改；所有写路径必经 kernel.submit（INV-1），结构/条件校验由提交管线强制。",
        '"""', ""]
    for a in actions:
        name, prov = a["action_type"], a.get("provenance", "UNKNOWN")
        decl_params = a.get("params", {}) or {}
        kwargs = []
        for pname, spec in decl_params.items():
            kwargs.append(f"{pname}" if (spec or {}).get("required") else f"{pname}=None")
        payload = "{" + ", ".join(f'"{k}": {k}' for k in decl_params) + "}"
        rules = "; ".join((a.get("submission_criteria", {}) or {}).get("structural", []))
        lines += [
            f"def {_snake(name)}(kernel, principal, *, {', '.join(kwargs) or '**_'}, roles=(), **snapshot):",
            f'    """{name}（provenance: {prov}）',
            f"    结构: {rules or '（无声明结构规则）'}",
            f"    条件: 由提交管线 R10 解释器强制（快照输入 R2 经 **snapshot 透传）",
            '    """',
            f'    payload = {payload}',
            f'    payload.update(snapshot)                    # 快照字段（R2）不属签名，透传',
            f'    return kernel.submit("{name}", payload, principal, roles=roles)',
            ""]
    return "\n".join(lines)
_KERNEL_FIELDS = {"valid_time", "projection_ref", "session_ref", "transaction_time"}
def _render_reducers(objects: list[dict]) -> str:
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— 声明驱动的投影 reducer（纯函数）。',
        f"spec_ref: {_spec_ref()} · 重放纯度: 无谓词、无宿主函数（KS-3.4 / R11）",
        "声明外字段进 _undeclared —— 语义漂移可见而非静默丢弃（KS-4.3 / GOV-6）。",
        '"""', "",
        "REDUCERS: dict = {}    # 聚合 → 投影 reducer（pipeline 条件快照物化，只读）",
        "IDENTITIES: dict = {}  # 聚合 → 实例标识属性（params 定位聚合实例）",
        ""]
    root_to_agg = {a.get("root"): a.get("aggregate")
                   for a in _load_dir("aggregates") if a.get("root")}
    for o in objects:
        otype = o["object_type"]
        agg = o.get("aggregate") or root_to_agg.get(otype, "")
        props = [k for k in (o.get("properties", {}) or {}) if k != o.get("identity")]
        var = otype.lower()
        lines += [
            f"{var.upper()}_DECLARED_PROPS = frozenset({props!r})",
            f'{var.upper()}_IDENTITY = "{o.get("identity", "")}"',
            f"def reduce_{var}(state, ev):",
            f'    """{otype} 投影折叠（由 {otype}.object.yaml 生成；纯函数）。"""',
            f"    obj = state.setdefault(ev.payload.get({var.upper()}_IDENTITY, \"_root\"), {{}})",
            f"    for k, v in ev.payload.items():",
            f"        if k == {var.upper()}_IDENTITY or k in {var.upper()}_DECLARED_PROPS:",
            "            obj[k] = v",
            f"        elif k not in {sorted(_KERNEL_FIELDS)!r} and not k.startswith(\"_\"):",
            '            obj.setdefault("_undeclared", {})[k] = v   # 声明外 → 漂移可见',
            "    return state",
            ""]
        if agg:
            lines += [f'REDUCERS.setdefault("{agg}", reduce_{var})',
                      f'IDENTITIES.setdefault("{agg}", {o.get("identity", "")!r})',
                      ""]
    return "\n".join(lines)
def _governance_authorizations() -> dict[str, list[dict]]:
    """action → 授权职责项列表（L4 锚点：生成码携带治理授权链，图1 → 图4）。"""
    out: dict[str, list[dict]] = {}
    for g in _load_dir("governance"):
        for d in g.get("duties", []) or []:
            for a in d.get("authorizes", []) or []:
                out.setdefault(a, []).append(d)
    return out
def _render_command_api(actions: list[dict]) -> str:
    """Command 端路由表：dispatch 只做路由；required_roles/duty 供网关与
    前端守卫消费；权限强制点唯一在 kernel.submit（INV-1，不复判无绕行）。"""
    authz = _governance_authorizations()
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— Command 端路由（CQRS 写侧）。',
        f"spec_ref: {_spec_ref()} · 门控: spec/profile.yaml backend.cqrs · 再生成: aos generate --force",
        "dispatch 只做路由与元数据暴露；写路径必经 kernel.submit（INV-1），",
        "required_roles / duty 是网关与前端守卫的对接面（OAuth2.1 claims 投影源）。",
        '"""', "",
        "from generated import actions as _actions",
        "",
        "ROUTES: dict = {}   # action_type → {method, handler, required_roles, duty, provenance}",
        ""]
    for a in actions:
        name, prov = a["action_type"], a.get("provenance", "UNKNOWN")
        fn = _snake(name)
        roles = tuple(sorted((a.get("permissions") or {}).get("roles") or []))
        duties = authz.get(name) or []
        duty = duties[0].get("duty", "") if duties else ""   # 授权链首个职责项
        lines += [
            f'ROUTES["{name}"] = {{',
            '    "method": "POST",',
            f'    "handler": "{fn}",                       # generated.actions.{fn}',
            f'    "required_roles": {roles!r},',
            f'    "duty": {duty!r},',
            f'    "provenance": "{prov}",',
            "}", ""]
    body = [
        "def dispatch(kernel, action_type, principal, *, roles=(), **params):",
        '    """命令路由：唯一写路径 = handler → kernel.submit（INV-1）。',
        '    未出示角色 = 无权（fail-closed，kernel P-10/INV-4 强制，此处不复判）。',
        '    """',
        '    route = ROUTES.get(action_type)',
        '    if route is None:',
        '        raise KeyError(f"UNROUTED: {action_type} 不在 Command 路由表内")',
        '    return getattr(_actions, route["handler"])(kernel, principal, roles=roles, **params)',
        ""]
    return "\n".join(["\n".join(lines), "\n".join(body)])
def _render_query_api(objects: list[dict]) -> str:
    """Query 端读侧：按聚合 identity 取数/列表。纯读、容错可重写（CQRS 读端）。"""
    idents = {o["object_type"]: (o.get("identity") or "") for o in objects}
    root_to_agg = {a.get("root"): a.get("aggregate")
                   for a in _load_dir("aggregates") if a.get("root")}
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— Query 端读侧（CQRS 读模型查询）。',
        f"spec_ref: {_spec_ref()} · 门控: spec/profile.yaml backend.cqrs · 再生成: aos generate --force",
        "纯读：只查投影状态，不触存储写路径（R11）；读端容错高，可整模块重写。",
        '"""', "",
        "QUERIES: dict = {}   # \u201c<Aggregate>.get|.list\u201d → 查询函数（投影状态 = reducer 折叠结果）",
        ""]
    for o in objects:
        root, agg = o["object_type"], o.get("aggregate") or root_to_agg.get(o["object_type"], "")
        var = _snake(root)
        ident = idents.get(root, "")
        lines += [
            f'{var.upper()}_IDENTITY = "{ident}"',
            f"def get_{var}(projection, {ident or 'identity'}):",
            f'    """读侧查询：{root} 按 identity 取（纯读）。"""',
            f'    return projection.get({ident or "identity"})',
            "",
            f"def list_{var}(projection):",
            f'    """读侧查询：{root} 全量列表（跳过折叠容器内部键）。"""',
            '    return [v for k, v in projection.items() if not str(k).startswith("_")]',
            ""]
        if agg:
            lines += [f'QUERIES["{agg}.get"] = get_{var}',
                      f'QUERIES["{agg}.list"] = list_{var}', ""]
    return "\n".join(lines)
def _governance_positions() -> dict[str, dict]:
    """岗位 → 治理投影（duties/org_units/authorizes）。claims 的唯一语义来源：
    roles 只能取声明岗位，duties/org_units 由声明推导，不可自报（图1 → Token）。"""
    out: dict[str, dict] = {}
    for g in _load_dir("governance"):
        for d in g.get("duties", []) or []:
            pos = d.get("position") or ""
            if not pos:
                continue
            e = out.setdefault(pos, {"duties": [], "org_units": set(), "authorizes": []})
            if d.get("duty") and d["duty"] not in e["duties"]:
                e["duties"].append(d["duty"])
            if d.get("org_unit"):
                e["org_units"].add(d["org_unit"])
            for a in d.get("authorizes") or []:
                if a not in e["authorizes"]:
                    e["authorizes"].append(a)
    for e in out.values():
        e["org_units"] = sorted(e["org_units"])
        e["authorizes"] = sorted(e["authorizes"])
    return out
def _render_auth_oauth(prof: dict) -> str:
    """OAuth 2.1 IdP 骨架（最小实现，声明驱动）。
    仅 Authorization Code + PKCE（S256）—— implicit/ROPC 无生成路径（OAuth 2.1 废除）；
    用户凭证校验属外部 authN（T03 在本体之外）：issue_token 强制绑定 assignment_ref
    （外部凭据引用，GOV-1 同构——CLI 只记录治理结果，不合成正当性）；
    claims 由治理面投影；DPoP（RFC 9449）按 profile 的 auth.token_binding 值生成。"""
    binding = str(prof.get("values", {}).get("auth.token_binding", "none")).lower()
    positions = _governance_positions()
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— OAuth 2.1 IdP 骨架（声明驱动）。',
        f"spec_ref: {_spec_ref()} · 门控: spec/profile.yaml auth.oauth2_1 · "
        f"token_binding: {binding} · 再生成: aos generate --force",
        "- 仅 Authorization Code + PKCE（S256）：implicit/ROPC 无生成路径（OAuth 2.1 废除）",
        "- 用户凭证校验属外部 authN（T03 在本体之外）：issue_token MUST 绑定 assignment_ref",
        "  （外部凭据引用；与 GOV-1 同构——不合成正当性，只挂接声明与引用）",
        "- claims 由治理面投影（GOV_POSITIONS）：roles ⊆ 声明岗位；duties/org_units 推导，不可自报",
        "- 签名密钥：环境变量 AOS_IDP_SECRET（缺失 → 签发/验证一律拒绝，fail-closed）",
        "- 客户端注册是部署期运行时动作（register_client）——生成物保持零漂移，不落密钥/客户清单",
        '"""', "",
        "import base64, hashlib, hmac, json, os, secrets, time",
        "",
        "class AuthRefused(Exception):",
        '    """认证/授权请求被拒（fail-closed：一切缺失 = 拒绝，不默认放行）。"""',
        "",
        f"TOKEN_BINDING = {binding!r}",
        "CODE_TTL = 600        # 授权码 10 分钟（OAuth 2.1 建议）",
        "TOKEN_TTL = 900       # 访问令牌 15 分钟",
        f"GOV_POSITIONS: dict = {positions!r}   # 治理面投影（再生成刷新，禁止手改）",
        "CLIENTS: dict = {}    # 部署期经 register_client 登记（生成物不携带客户清单）",
        "_CODES: dict = {}     # 授权码（一次性，内存态；重启即失效 = fail-closed）",
        "_GRANTS: dict = {}",
        "",
        "def register_client(client_id: str, redirect_uris: list[str], scopes=()) -> None:",
        '    """部署期客户端登记：redirect_uri 白名单是授权码拦截攻击的防线。"""',
        "    if not client_id or not redirect_uris:",
        '        raise AuthRefused("CLIENT-INVALID: client_id 与 redirect_uris 必填")',
        "    CLIENTS[client_id] = {\"redirect_uris\": list(redirect_uris),",
        "                          \"scopes\": tuple(scopes)}",
        "",
        "def _b64u(b: bytes) -> str:",
        '    return base64.urlsafe_b64encode(b).rstrip(b"=").decode("ascii")',
        "",
        "def _secret() -> bytes:",
        '    s = os.environ.get("AOS_IDP_SECRET")',
        '    if not s:',
        '        raise AuthRefused("SECRET-MISSING: 环境变量 AOS_IDP_SECRET 未配置 ——"',
        '                          " 不签发不验证（fail-closed）")',
        '    return s.encode("utf-8")',
        "",
        "def begin_authorization(client_id, redirect_uri, scope, code_challenge,",
        "                        challenge_method):",
        '    """授权端点：PKCE 必须 S256（plain 在 OAuth 2.1 已废除）。"""',
        "    cli = CLIENTS.get(client_id)",
        "    if cli is None:",
        '        raise AuthRefused(f"CLIENT-UNKNOWN: {client_id} 未登记")',
        "    if redirect_uri not in cli[\"redirect_uris\"]:",
        '        raise AuthRefused("REDIRECT-UNREGISTERED: redirect_uri 不在白名单内"',
        '                          "（授权码拦截防线）")',
        "    if challenge_method != \"S256\":",
        '        raise AuthRefused("PKCE-METHOD-REFUSED: 仅 S256（OAuth 2.1 废除 plain）")',
        "    code = secrets.token_urlsafe(32)",
        "    _CODES[code] = {\"client_id\": client_id, \"redirect_uri\": redirect_uri,",
        "                    \"scope\": tuple(scope or ()),",
        "                    \"challenge\": code_challenge,",
        "                    \"exp\": time.time() + CODE_TTL, \"used\": False}",
        "    return code",
        "",
        "def exchange_code(client_id, code, redirect_uri, code_verifier):",
        '    """令牌端点第一段：一次性授权码 + PKCE 校验 → 授权许可（grant）。',
        '    grant 本身不含身份——身份与治理角色在 issue_token 绑定（两段分离，',
        '    授权码泄漏不等于角色泄漏）。',
        '    """',
        "    rec = _CODES.get(code)",
        "    if rec is None or rec[\"used\"]:",
        '        raise AuthRefused("CODE-INVALID: 授权码无效或已使用（一次性）")',
        "    if time.time() > rec[\"exp\"]:",
        '        raise AuthRefused("CODE-EXPIRED: 授权码过期")',
        "    if rec[\"client_id\"] != client_id or rec[\"redirect_uri\"] != redirect_uri:",
        '        raise AuthRefused("CODE-MISMATCH: client/redirect 与发起时不一致")',
        "    if _b64u(hashlib.sha256(code_verifier.encode()).digest()) != rec[\"challenge\"]:",
        '        raise AuthRefused("PKCE-FAILED: verifier 与 challenge 不匹配")',
        "    rec[\"used\"] = True",
        "    grant = secrets.token_urlsafe(32)",
        "    _GRANTS[grant] = {\"client_id\": client_id, \"scope\": rec[\"scope\"],",
        "                      \"exp\": time.time() + CODE_TTL}",
        "    return grant",
        "",
        "def issue_token(grant, principal, roles, assignment_ref, dpop_jkt=None):",
        '    """令牌端点第二段：签发 JWT。roles ⊆ 治理面声明岗位（UNDECLARED-POSITION',
        '    拒绝）；duties/org_units 由 GOV_POSITIONS 推导，调用方不可自报；',
        '    assignment_ref 必填（外部 authN 凭据引用，T03/GOV-1 同构）；',
        '    token_binding=dpop 时 MUST 绑定 cnf.jkt（RFC 9449 证明者拇指印）。',
        '    """',
        "    if grant not in _GRANTS or time.time() > _GRANTS[grant][\"exp\"]:",
        '        raise AuthRefused("GRANT-INVALID: 授权许可无效或过期")',
        "    if not principal or not assignment_ref:",
        '        raise AuthRefused("PRINCIPAL-REFS-REQUIRED: (principal, assignment_ref) 必填 —— 用户凭证校验属外部 authN（T03），此处只挂接凭据引用，不合成正当性")',
        "    undeclared = [r for r in (roles or ()) if r not in GOV_POSITIONS]",
        "    if undeclared:",
        '        raise AuthRefused(f"UNDECLARED-POSITION: {undeclared} 不在治理面声明岗位内 —— claims 只能投影声明角色（fail-closed）")',
        "    duties: list = []",
        "    orgs: list = []",
        "    for r in roles or ():",
        "        for d in GOV_POSITIONS[r][\"duties\"]:",
        "            if d not in duties: duties.append(d)",
        "        for o in GOV_POSITIONS[r][\"org_units\"]:",
        "            if o not in orgs: orgs.append(o)",
        "    claims = {\"sub\": principal,",
        "              \"roles\": sorted(roles or ()),",
        "              \"duties\": sorted(duties),",
        "              \"org_units\": sorted(orgs),",
        "              \"authorizes\": sorted({a for r in roles or ()",
        "                                    for a in GOV_POSITIONS[r][\"authorizes\"]}),",
        "              \"asg\": assignment_ref,",
        "              \"scope\": sorted(_GRANTS[grant][\"scope\"]),",
        "              \"iss\": \"aos-idp\",",
        "              \"iat\": int(time.time()), \"exp\": int(time.time()) + TOKEN_TTL,",
        "              \"jti\": secrets.token_urlsafe(16)}",
        "    if TOKEN_BINDING == \"dpop\":",
        "        if not dpop_jkt:",
        '            raise AuthRefused("DPOP-REQUIRED: token_binding=dpop 时 MUST 提供证明者拇指印（RFC 9449 cnf.jkt）")',
        "        claims[\"cnf\"] = {\"jkt\": dpop_jkt}",
        "    elif TOKEN_BINDING == \"mTLS\":",
        '        raise AuthRefused("MTLS-EXTERNAL: 证书绑定属 TLS 终端，由部署层反向通道实现（诚实边界，模板不模拟）")',
        "    return _jwt(claims)",
        "",
        "def _jwt(claims: dict) -> str:",
        '    header = {"alg": "HS256", "typ": "JWT"}',
        "    si = (_b64u(json.dumps(header, separators=(',', ':'), sort_keys=True).encode())",
        "          + '.' +",
        "          _b64u(json.dumps(claims, separators=(',', ':'), sort_keys=True).encode()))",
        "    return si + '.' + _b64u(hmac.new(_secret(), si.encode(), hashlib.sha256).digest())",
        "",
        "def verify_token(token: str, dpop_jkt=None) -> dict:",
        '    """资源服务器侧验签：签名（恒时比较）· exp · cnf.jkt 绑定核对。',
        '    绑定令牌未随证明（dpop_jkt 缺失）→ 拒绝（防令牌重放）。',
        '    """',
        "    try:",
        "        si, sig = token.rsplit(\".\", 1)",
        "        ok = hmac.compare_digest(",
        "            _b64u(hmac.new(_secret(), si.encode(), hashlib.sha256).digest()), sig)",
        "    except Exception as e:",
        '        raise AuthRefused(f"TOKEN-MALFORMED: {e}") from e',
        "    if not ok:",
        '        raise AuthRefused("TOKEN-SIGNATURE: 验签失败")',
        "    claims = json.loads(base64.urlsafe_b64decode(si.split('.')[1] + '=='))",
        "    if time.time() > claims.get(\"exp\", 0):",
        '        raise AuthRefused("TOKEN-EXPIRED")',
        "    if \"cnf\" in claims:",
        "        if not dpop_jkt:",
        '            raise AuthRefused("PROOF-REQUIRED: 绑定令牌 MUST 随 DPoP 证明重放（防令牌窃取重放，RFC 9449）")',
        "        if dpop_jkt != claims[\"cnf\"][\"jkt\"]:",
        '            raise AuthRefused("PROOF-MISMATCH: 证明者与令牌绑定不一致")',
        "    return claims",
        "",
        "def authorize(action_type: str, claims: dict) -> dict:",
        '    """资源服务器拦截器：token claims → Command 路由所需角色对账。',
        '    required_roles 来自治理授权链（command_api.ROUTES，声明驱动）；',
        '    未启用 backend.cqrs 时拒绝（诚实边界）。',
        '    """',
        "    try:",
        "        from generated import command_api as _cmd",
        "    except ImportError as e:",
        '        raise AuthRefused("COMMAND-API-ABSENT: backend.cqrs 未启用 —— 无路由可对账") from e',
        "    route = _cmd.ROUTES.get(action_type)",
        "    if route is None:",
        '        raise AuthRefused(f"UNROUTED: {action_type} 不在 Command 路由表内")',
        "    have = set(claims.get(\"roles\") or ())",
        "    need = set(route[\"required_roles\"])",
        "    if not need <= have:",
        "        missing, present = sorted(need - have), sorted(have) or [\"\\u2205\"]",
        "        raise AuthRefused(f\"ROLE-MISMATCH: {action_type} 需要 {missing}，\"",
        "                          f\"令牌出示 {present}\")",
        "    return route",
        ""]
    return "\n".join(lines)
def _render_admin_console(actions: list[dict], objects: list[dict]) -> str:
    """前端控制台元数据层（frontend.admin_console）：GUARD / PAGES / FORMS 三张
    声明驱动表 + fail-closed 守卫。GUARD 与 command_api.ROUTES 同源（治理授权链）；
    诚实边界：这里生成的是前端消费的元数据与路由守卫（can_access/nav_for），
    具体 UI 组件（表单/列表渲染）由实例前端框架消费这些表 —— 生成物不含 UI 库。"""
    authz = _governance_authorizations()
    guard, forms = {}, {}
    for a in actions:
        name = a["action_type"]
        roles = tuple(sorted((a.get("permissions") or {}).get("roles") or []))
        duties = authz.get(name) or []
        guard[name] = {"required_roles": list(roles),
                       "duty": duties[0].get("duty", "") if duties else ""}
        forms[name] = {p: (s.get("type", "string") if isinstance(s, dict) else str(s))
                       for p, s in (a.get("params") or {}).items()}
    pages = {}
    for o in objects:
        fields = [k for k in (o.get("properties") or {})
                  if isinstance(o["properties"][k], dict)]
        pages[o["object_type"]] = {"identity": o.get("identity") or "",
                                   "fields": fields}
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— 前端控制台元数据层（声明驱动）。',
        f"spec_ref: {_spec_ref()} · 门控: spec/profile.yaml frontend.admin_console · 再生成: aos generate --force",
        "- GUARD 与 command_api.ROUTES 同源（治理授权链）：roles/duty 由声明定，前端不可自报",
        "- can_access fail-closed：GUARD 未列的动作一律拒绝；未出示所需角色一律拒绝",
        "- FORMS/PAGES 是 UI 消费的 schema（表单字段/列表列），不含 UI 库（实例侧框架消费）",
        '"""', "",
        f"GUARD: dict = {guard!r}",
        f"FORMS: dict = {forms!r}",
        f"PAGES: dict = {pages!r}",
        "",
        "def can_access(action_type, roles=()) -> bool:",
        '    """路由守卫：声明驱动对账（fail-closed —— 与内核 INV-4 同向，不复判写路径）。"""',
        '    g = GUARD.get(action_type)',
        "    if g is None:",
        "        return False                     # 未列动作 = 无此能力（fail-closed）",
        "    return bool(set(g[\"required_roles\"]) & set(roles))",
        "",
        "def nav_for(roles=()) -> dict:",
        '    """按角色过滤可见导航：页面 → 可发起动作（仅 GUARD 放行的）。"""',
        "    acts = [a for a in GUARD if can_access(a, roles)]",
        "    return {p: {\"fields\": v[\"fields\"], \"actions\": acts} for p, v in PAGES.items()}",
        "",
    ]
    return "\n".join(lines)
