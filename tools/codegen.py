#!/usr/bin/env python3
"""tools/codegen.py —— 声明 → 代码骨架生成器（AI 软件工厂缺口 ② 的兑现点）。
输入：spec/ 八类声明（必须先通过 compile_all —— 不可编译即拒绝生成，KS-7.1）
输出：src/generated/{__init__,actions,reducers}.py
- actions.py   每个已注册 Action 一个 handler：只封装 kernel.submit（INV-1，
               写路径必经同一条管线）；结构/条件校验由提交管线强制，骨架不复制逻辑；
- reducers.py  每个 object 一个投影 reducer：纯函数（R11 / KS-3.4），
               只物化声明内属性；声明外字段进 _undeclared —— 语义漂移可见（KS-4.3）；
- 溯源：文件头携带 spec_ref 与每条声明 provenance（GOV-2.2 的代码形态）；
- 手改检测：已存在且与再生成结果字节不一致 → 拒绝（禁止静默覆盖人工代码）；
  --force 显式覆盖（正常路径：改声明 → 重新生成）。
"""
from __future__ import annotations
import re
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "src"))
import yaml
from kernel.registration import compile_all, load_caps
class CodegenDrift(Exception):
    """生成物被手改（与声明驱动的再生成结果不一致）—— 禁止静默覆盖。"""
OUT_DIR = ROOT / "src/generated"
def _snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
def _load_dir(sub: str) -> list[dict]:
    out = []
    for p in sorted((ROOT / "spec" / sub).glob("*.yaml")):
        out.append(yaml.safe_load(p.read_text(encoding="utf-8")) or {})
    return out
def _spec_ref() -> str:
    caps = load_caps()
    m = re.search(r"spec_ref:\s*(AOS-ART-\d+)",
                  (ROOT / "config/capabilities.yaml").read_text(encoding="utf-8"))
    return m.group(1) if m else str(caps.get("spec_ref", "UNKNOWN"))
def _render_actions(actions: list[dict]) -> str:
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— 声明即代码（KS-4.3 的骨架形态）。',
        f"spec_ref: {_spec_ref()} · 再生成: aos generate --force（正常路径先改 spec/ 声明）",
        "禁止手改；所有写路径必经 kernel.submit（INV-1），结构/条件校验由提交管线强制。",
        '"""', ""]
    for a in actions:
        name, prov = a["action_type"], a.get("provenance", "UNKNOWN")
        decl_params = a.get("params", {}) or {}
        kwargs = []
        for pname, spec in decl_params.items():
            kwargs.append(f"{pname}" if (spec or {}).get("required") else f"{pname}=None")
        payload = "{" + ", ".join(f'"{k}": {k}' for k in decl_params) + "}"
        rules = "; ".join((a.get("submission_criteria", {}) or {}).get("structural", []))
        lines += [
            f"def {_snake(name)}(kernel, principal, *, {', '.join(kwargs) or '**_'}, **snapshot):",
            f'    """{name}（provenance: {prov}）',
            f"    结构: {rules or '（无声明结构规则）'}",
            f"    条件: 由提交管线 R10 解释器强制（快照输入 R2 经 **snapshot 透传）",
            '    """',
            f'    payload = {payload}',
            f'    payload.update(snapshot)                    # 快照字段（R2）不属签名，透传',
            f'    return kernel.submit("{name}", payload, principal)',
            ""]
    return "\n".join(lines)
_KERNEL_FIELDS = {"valid_time", "projection_ref", "session_ref", "transaction_time"}
def _render_reducers(objects: list[dict]) -> str:
    lines = [
        '"""AUTO-GENERATED by tools/codegen.py —— 声明驱动的投影 reducer（纯函数）。',
        f"spec_ref: {_spec_ref()} · 重放纯度: 无谓词、无宿主函数（KS-3.4 / R11）",
        "声明外字段进 _undeclared —— 语义漂移可见而非静默丢弃（KS-4.3 / GOV-6）。",
        '"""', ""]
    for o in objects:
        otype = o["object_type"]
        props = [k for k in (o.get("properties", {}) or {}) if k != o.get("identity")]
        var = otype.lower()
        lines += [
            f"{var.upper()}_DECLARED_PROPS = frozenset({props!r})",
            f'{var.upper()}_IDENTITY = "{o.get("identity", "")}"',
            f"def reduce_{var}(state, ev):",
            f'    """{otype} 投影折叠（由 {otype}.object.yaml 生成；纯函数）。"""',
            f"    obj = state.setdefault(ev.payload.get({var.upper()}_IDENTITY, \"_root\"), {{}})",
            f"    for k, v in ev.payload.items():",
            f"        if k == {var.upper()}_IDENTITY or k in {var.upper()}_DECLARED_PROPS:",
            "            obj[k] = v",
            f"        elif k not in {sorted(_KERNEL_FIELDS)!r} and not k.startswith(\"_\"):",
            '            obj.setdefault("_undeclared", {})[k] = v   # 声明外 → 漂移可见',
            "    return state",
            ""]
    return "\n".join(lines)
def generate(force: bool = False) -> dict:
    compile_all()                                   # 不可编译声明 → 拒绝生成（KS-7.1 前置）
    actions = _load_dir("ontology/actions")
    objects = _load_dir("ontology/objects")
    files = {
        "__init__.py": '"""AUTO-GENERATED by tools/codegen.py —— 声明驱动的代码骨架。"""\n',
        "actions.py": _render_actions(actions),
        "reducers.py": _render_reducers(objects),
    }
    # 字节级比对与写入（GOV-2.3 / .gitattributes `* -text`）：Windows 的
    # write_text 把 \n 落成 \r\n，而 read_text 又把 \r\n 读回 \n —— 文本比较
    # 会掩盖换行漂移，"骨架零漂移" 判据因此失效。签发制品必须字节精确。
    drift = []
    for rel, src in files.items():
        p = OUT_DIR / rel
        if p.exists() and p.read_bytes() != src.encode("utf-8"):
            drift.append(rel)
    if drift and not force:
        raise CodegenDrift(
            f"生成物与手改内容不一致（字节级）: {drift} —— 禁止静默覆盖；"
            f"确认后执行 aos generate --force（正常路径：先改 spec/ 声明再生成）")
    OUT_DIR.mkdir(exist_ok=True)
    for rel, src in files.items():
        (OUT_DIR / rel).write_bytes(src.encode("utf-8"))
    return {"files": sorted(files), "actions": [a["action_type"] for a in actions],
            "objects": [o["object_type"] for o in objects]}
def main(force: bool = False) -> int:
    try:
        report = generate(force)
    except CodegenDrift as e:
        print(f"CODEGEN-DRIFT-REFUSED: {e}"); return 1
    print(f"GENERATED: {report['files']} ｜ actions: {report['actions']} ｜ "
          f"objects: {report['objects']} → src/generated/")
    return 0
if __name__ == "__main__":
    sys.exit(main("--force" in sys.argv))
